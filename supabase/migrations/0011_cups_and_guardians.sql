create table public.cups (
  id bigint generated by default as identity primary key,
  name text not null,
  start_date date not null,
  end_date date not null,
  venue text not null default '',
  period_minutes integer not null default 18 check (period_minutes between 1 and 60),
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);

create unique index cups_name_start_unique on public.cups (lower(name), start_date);

create table public.cup_teams (
  id bigint generated by default as identity primary key,
  cup_id bigint not null references public.cups(id) on delete cascade,
  name text not null,
  sort_order integer not null default 1 check (sort_order > 0),
  unique (cup_id, name),
  unique (cup_id, id)
);

create table public.cup_team_players (
  cup_id bigint not null,
  cup_team_id bigint not null,
  player_id bigint not null references public.players(id) on delete cascade,
  primary key (cup_id, player_id),
  foreign key (cup_id, cup_team_id) references public.cup_teams(cup_id, id) on delete cascade
);
create index cup_team_players_team_idx on public.cup_team_players(cup_team_id);
create index cup_team_players_cup_team_idx on public.cup_team_players(cup_id,cup_team_id);
create index cup_team_players_player_idx on public.cup_team_players(player_id);

create table public.player_guardians (
  player_id bigint not null references public.players(id) on delete cascade,
  user_id bigint not null references public.app_users(id) on delete cascade,
  primary key (player_id, user_id)
);
create index player_guardians_user_idx on public.player_guardians(user_id);

alter table public.matches add column cup_id bigint;
alter table public.matches add column cup_team_id bigint;
alter table public.matches add constraint matches_cup_team_fk
  foreign key (cup_id, cup_team_id) references public.cup_teams(cup_id, id) on delete cascade;

alter table public.cups enable row level security;
alter table public.cup_teams enable row level security;
alter table public.cup_team_players enable row level security;
alter table public.player_guardians enable row level security;
revoke all on public.cups, public.cup_teams, public.cup_team_players, public.player_guardians from public, anon, authenticated;

